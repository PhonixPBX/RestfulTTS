#!/bin/sh
# Refresh vendored front-end assets (Tabler + Tabler icons + htmx 4), same versions as PhonixPBX.
# Only the files the UI uses are copied; versions + SHA256 go to vendor/VERSIONS.
set -eu

TABLER_VERSION=1.7.1
ICONS_VERSION=3.49.0
HTMX_VERSION=4.0.0

ROOT=$(cd "$(dirname "$0")/.." && pwd)
DEST="$ROOT/src/restfultts/static/vendor"
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

cd "$WORK"
npm pack --silent "@tabler/core@$TABLER_VERSION" "@tabler/icons-webfont@$ICONS_VERSION" "htmx.org@$HTMX_VERSION" >/dev/null
for t in *.tgz; do mkdir "${t%.tgz}" && tar xzf "$t" -C "${t%.tgz}"; done

T="$WORK/tabler-core-$TABLER_VERSION/package"
I="$WORK/tabler-icons-webfont-$ICONS_VERSION/package/dist"
H="$WORK/htmx.org-$HTMX_VERSION/package"

rm -rf "$DEST"
mkdir -p "$DEST"/tabler "$DEST"/icons/fonts "$DEST"/htmx
cp "$T/dist/css/tabler.min.css" "$T/dist/js/tabler.min.js" "$T/dist/js/tabler-theme.min.js" "$DEST/tabler/"
cp "$T/LICENSE" "$DEST/tabler/LICENSE" 2>/dev/null || true
cp "$I/tabler-icons.min.css" "$DEST/icons/"
cp "$I/fonts/tabler-icons.woff2" "$DEST/icons/fonts/"
# the CSS also references woff/ttf - drop those fallbacks (all supported browsers do woff2)
sed -i -E 's#,url\("?\./fonts/tabler-icons\.woff\?[^)]*\)[^,;]*##g; s#,url\("?\./fonts/tabler-icons\.ttf\?[^)]*\)[^,;}]*##g' \
    "$DEST/icons/tabler-icons.min.css"
cp "$H/dist/htmx.min.js" "$H/LICENSE" "$DEST/htmx/"

{
    echo "# Vendored front-end assets - generated by scripts/vendor-update.sh"
    echo "@tabler/core $TABLER_VERSION"
    echo "@tabler/icons-webfont $ICONS_VERSION"
    echo "htmx.org $HTMX_VERSION"
    echo
    cd "$DEST" && find . -type f ! -name VERSIONS | sort | xargs sha256sum
} > "$DEST/VERSIONS"
echo "vendored into $DEST"
